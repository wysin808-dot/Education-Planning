export interface Programme {
  id: string;
  /** 专业英文名 */
  name: string;
  /** 专业中文名 */
  nameZh: string;
  /** 学科大类，用于按兴趣方向反查 */
  field: FieldKey;
  /**
   * 官方公布的 ATAR 门槛。若院校未按专业单列门槛，则沿用全校最低门槛并在 atarNote 说明。
   * null 表示官方未公布任何可用数值。
   */
  atar: number | null;
  /** 竞争性分数：官方或往年实际录取显著高于最低门槛时标注 */
  atarNote?: string;
  /** 必需先修科目（满足其一即可的用「或」表达在同一字符串内） */
  prerequisites: SubjectKey[][];
  /** 先修科目的文字说明，保留官方原始口径 */
  prerequisiteNote?: string;
  extras: ExtraRequirement[];
}

